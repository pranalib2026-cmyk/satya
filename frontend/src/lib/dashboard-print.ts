/** Opens a print window for the given HTML. Used for "Download as PDF". */
export function printHtml(title: string, bodyHtml: string) {
  const win = window.open("", "_blank", "width=820,height=1000");
  if (!win) {
    alert("Please allow pop-ups to download the PDF.");
    return;
  }
  win.document.write(`<!doctype html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${title}</title>
  <style>
    * { box-sizing: border-box; }
    body { font-family: Georgia, 'Times New Roman', serif; color: var(--color-ink, #2a1c12); margin: 0; padding: 48px; font-size: 13.5px; line-height: 1.75; }
    h1 { font-size: 18px; letter-spacing: .04em; }
    pre { font-family: inherit; white-space: pre-wrap; margin: 0; }
    .footer { margin-top: 32px; padding-top: 12px; border-top: 1px solid var(--color-line, #e2d5c1); font-family: Arial, sans-serif; font-size: 10px; color: var(--color-muted, #85725f); }
    @page { margin: 18mm; }
  </style>
</head>
<body>
  <pre>${bodyHtml}</pre>
  <div class="footer">Template generated by NyayaSetu. Legal information only — not legal advice. Advocate review recommended before filing.</div>
</body>
</html>`);
  win.document.close();
  win.focus();
  setTimeout(() => win.print(), 350);
}
